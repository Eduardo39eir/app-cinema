export const today = () => {
  const d = new Date();
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
};
export function dayOffset(n: number) {
  const d = new Date();
  d.setDate(d.getDate() + n);
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
}
export const formatDate = (
  date: string,
  opts: Intl.DateTimeFormatOptions = { day: "2-digit", month: "short" },
) => {
  const formatted = new Date(date + "T12:00:00").toLocaleDateString(
    "pt-BR",
    opts,
  );
  return opts.month === "short" ? formatted.replace(" de ", " ") : formatted;
};
