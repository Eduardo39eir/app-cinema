export function makeSessions(): Session[] {
  return movies
    .filter((m) => m.cinema)
    .flatMap((m, mi) =>
      Array.from({ length: 7 }, (_, d) =>
        cinemas.flatMap((c, ci) =>
          ["16:00", "19:00", "21:30"].map((time, ti) => ({
            id: `${m.id}-${dayOffset(d)}-${ci}-${ti}`,
            movieId: m.id,
            cinemaId: c.id,
            date: dayOffset(d),
            time,
            language: ti === 0 ? "Dublado" : "Legendado",
            format: ci === 0 ? "2D · Dolby Atmos" : "2D",
            room: `0${ti + 1}`,
            price: 28 + ci * 6 + ti * 4,
            occupied: [
              "A3",
              "A4",
              "B6",
              "C3",
              "C4",
              "D5",
              `${String.fromCharCode(65 + ((mi + ci + ti) % 6))}7`,
            ],
          })),
        ),
      ),
    )
    .flat();
}
